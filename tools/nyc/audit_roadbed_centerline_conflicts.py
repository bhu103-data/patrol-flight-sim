#!/usr/bin/env python3
"""Independent 1:1 NYC DCM centerline vs OTI roadbed/building consistency gate.

READ ONLY: consumes same-source metre QA JSON generated by #234/#244. Uses
GEOS via open-source Shapely to intersect genuine polygons *with holes*.
Never shifts a feature to make a conflict vanish and never edits PATROL game.
"""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

from shapely.geometry import LineString, Polygon
from shapely.strtree import STRtree

FOCUS_BUILDING_FID = 981369
FOCUS_DCM_OBJECTID = 1712
SOURCE_ROADBED = ("https://services6.arcgis.com/yG5s3afENB5iO9fj/"
                  "ArcGIS/rest/services/Roadbed_2022/FeatureServer/20")


def valid_polygon(shell, holes=None, label="polygon"):
    poly = Polygon(shell, holes or [])
    if poly.is_empty or not poly.is_valid or poly.area <= 0:
        raise ValueError(f"Invalid source {label} -- do not silently repair geometry")
    return poly


def geo_source(city, roadbed):
    if city.get("assetRole") != "GEOREFERENCED_SOURCE_QA_ONLY_NOT_IN_GAME":
        raise ValueError("Expected source-only non-production NYC metre geometry")
    if roadbed.get("schema") != "patrol-nyc-oti-roadbed-planimetric-2022-v1":
        raise ValueError("Unexpected NYC OTI measured roadbed schema")
    origin = city.get("projection", {}).get("originLonLat")
    if not origin or origin != roadbed.get("projection", {}).get("originLonLat"):
        raise ValueError("CRS/origin mismatch: DO NOT overlay these features")
    if city["projection"].get("scaleMetresPerGameUnit", "missing") is not None:
        raise ValueError("Compressed PATROL coordinates forbidden in this audit")
    return origin


def analyze(city, roadbed, focus_fid=FOCUS_BUILDING_FID,
            focus_dcm=FOCUS_DCM_OBJECTID):
    origin = geo_source(city, roadbed)
    buildings = {}
    for b in city.get("buildings", []):
        fid = b.get("fid")
        if fid in buildings:
            raise ValueError("Duplicate building FID")
        buildings[fid] = valid_polygon(b["outline"], label=f"building FID={fid}")
    surfaces = []
    for feature in roadbed.get("roadbeds", []):
        for i, rings in enumerate(feature["polygons"]):
            p = valid_polygon(rings[0], rings[1:],
                              f"roadbed ID={feature['objectId']} component={i}")
            surfaces.append((feature["objectId"], feature["subtype"], p))
    if not surfaces or not buildings:
        raise ValueError("Missing genuine official building/roadbed data")
    b_geoms = list(buildings.values())
    tree = STRtree([x[2] for x in surfaces])
    overlapping = []
    # Full cross-dataset check: city buildings against actual roadbed/driveway
    # and intersection polygons, NOT against schematic centerline guide lines.
    for fid, b in buildings.items():
        for idx in tree.query(b):
            road_id, subtype, polygon = surfaces[int(idx)]
            a = b.intersection(polygon).area
            if a > 0.01:  # tiny sub-decimetre² coincidences are noise
                overlapping.append({
                    "buildingFid": fid, "roadbedObjectId": road_id,
                    "roadbedSubtype": subtype, "overlapSquareMetres": round(a, 4)
                })
    overlapping.sort(key=lambda x: (-x["overlapSquareMetres"],
                                     x["buildingFid"], x["roadbedObjectId"]))
    focus_building = buildings.get(focus_fid)
    focus_road = next((r for r in city["roads"]
                       if r["objectId"] == focus_dcm), None)
    if focus_building is None or focus_road is None:
        raise ValueError("Source refresh lost the known conflict FID / DCM ID")
    line_intersection = sum(LineString(part).intersection(focus_building).length
                            for part in focus_road["lines"])
    reference = next((i for i in city.get(
        "sourceRoadBuildingOverlapAudit", {}).get("issues", [])
        if i.get("buildingFid") == focus_fid and
        i.get("roadObjectId") == focus_dcm), None)
    if reference and abs(line_intersection-reference["overlapMetres"]) > 0.02:
        raise ValueError("Existing DCM audit disagrees with direct GEOS length")
    measured_building_roadbed_area = sum(
        x["overlapSquareMetres"] for x in overlapping
        if x["buildingFid"] == focus_fid)
    nearest = min((focus_building.distance(poly), rid)
                  for rid, _, poly in surfaces)
    classification = ("centerline_only_no_roadbed_overlap"
                      if line_intersection > 0.1 and
                      measured_building_roadbed_area <= 0.01
                      else "REVIEW_REQUIRED")
    return {
        "schema": "patrol-nyc-dcm-vs-measured-roadbed-conflict-audit-v1",
        "assetRole": "QA_ONLY_NOT_GAME_COLLISION_OR_ROUTE_MAP",
        "sources": {
            "buildings": city["source"]["buildings"],
            "dcmCenterlines": city["source"]["streets"],
            "oti2022Roadbeds": SOURCE_ROADBED,
            "roadbedReferenceImageryYear": roadbed.get("referenceImageryYear")
        },
        "originWgs84": origin,
        "counts": {
            "buildings": len(buildings),
            "roadbedFeatures": len(roadbed["roadbeds"]),
            "roadbedComponents": len(surfaces),
            "roadbedBuildingAreaOverlaps": len(overlapping)
        },
        "roadbedBuildingOverlaps": overlapping,
        "focus": {
            "buildingFid": focus_fid, "dcmObjectId": focus_dcm,
            "dcmName": focus_road["streetName"],
            "centerlineInsideBuildingMetres": round(line_intersection, 4),
            "officialRoadbedInsideBuildingSquareMetres":
                round(measured_building_roadbed_area, 4),
            "nearestOfficialRoadbedEdgeMetres": round(nearest[0], 3),
            "nearestRoadbedObjectId": nearest[1],
            "classification": classification
        },
        "caveats": [
            "DCM centerline is a representation, not the physical roadbed footprint",
            "OTI ROADBED source geometry dates to 2022 imagery/2023 mapping, not 2026 as-built",
            "Building and roadbed sources may represent different dates and mapping standards",
            "This cannot infer actual curb heights, drivable lanes or vehicle routing",
            "No local aerial/street-view image or paid 3D map is copied"
        ]
    }


def focus_svg(city, roadbed, report):
    """Actual local coordinate plan, no guessed pixels, geometry or photography."""
    fid = report["focus"]["buildingFid"]
    rid = report["focus"]["dcmObjectId"]
    target = next(b for b in city["buildings"] if b["fid"] == fid)
    path = next(r for r in city["roads"] if r["objectId"] == rid)
    xs = [p[0] for p in target["outline"]]
    ys = [p[1] for p in target["outline"]]
    x0, x1 = min(xs)-95, max(xs)+95
    y0, y1 = min(ys)-95, max(ys)+95
    width, height = x1-x0, y1-y0
    def coords(ring):
        return " ".join(f"{p[0]:.3f},{-p[1]:.3f}" for p in ring)
    def ringpath(ring):
        return "M" + " L".join(f"{p[0]:.3f},{-p[1]:.3f}" for p in ring) + " Z"
    polygons = []
    for road in roadbed["roadbeds"]:
        for rings in road["polygons"]:
            # Show all 2022 official roadbed contours, including holes (evenodd).
            if not any(x0 <= p[0] <= x1 and y0 <= p[1] <= y1
                       for p in rings[0]):
                continue
            polygons.append('<path d="'+" ".join(map(ringpath, rings))+
                            '" fill="#4b8b70" stroke="#8cdabc" stroke-width=".5"'
                            ' fill-rule="evenodd"/>')
    centerline = "".join(
        '<polyline points="'+coords(part)+
        '" fill="none" stroke="#ffad5c" stroke-width="1.6"'
        ' stroke-dasharray="3 1.5"/>' for part in path["lines"])
    building = ('<polygon points="'+coords(target["outline"])+
                '" fill="#b34956" stroke="#fff3a5" stroke-width=".9"/>')
    label = escape(str(report["focus"]["classification"]))
    # Origin markers and bounds have 1:1 metre units; no axis stretching.
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="'+
            f"{x0:.3f} {-y1:.3f} {width:.3f} {height:.3f}"+
            '" width="900" height="900"><rect x="'+f"{x0:.3f}"+
            '" y="'+f"{-y1:.3f}"+'" width="'+f"{width:.3f}"+
            '" height="'+f"{height:.3f}"+
            '" fill="#10202e"/>'+"".join(polygons)+centerline+building+
            '<text x="'+f"{x0+6:.3f}"+'" y="'+f"{-y1+9:.3f}"+
            '" font-size="5" fill="#fff">FID '+str(fid)+
            ' vs DCM '+str(rid)+'</text>'+
            '<text x="'+f"{x0+6:.3f}"+'" y="'+f"{-y1+15:.3f}"+
            '" font-size="4" fill="#fff">'+label+'</text></svg>')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--city", default="artifacts/nyc-true-scale/source.json")
    parser.add_argument("--roadbed", default="artifacts/nyc-roadbed-source/roadbed.json")
    parser.add_argument("--out", default="artifacts/nyc-roadbed-alignment")
    opts = parser.parse_args()
    city = json.loads(Path(opts.city).read_text())
    roadbed = json.loads(Path(opts.roadbed).read_text())
    report = analyze(city, roadbed)
    out = Path(opts.out)
    out.mkdir(parents=True, exist_ok=True)
    (out/"report.json").write_text(json.dumps(report, indent=2)+"\n")
    (out/"focus-centerline-vs-roadbed.svg").write_text(focus_svg(city, roadbed, report))
    print("NYC DCM/OTI source alignment", json.dumps({
        "counts": report["counts"], "focus": report["focus"]}))
    if report["counts"]["roadbedBuildingAreaOverlaps"]:
        raise ValueError("Official 2022 roadbed physically overlaps buildings; REVIEW")
    if report["focus"]["classification"] != "centerline_only_no_roadbed_overlap":
        raise ValueError("DCM/roadbed focus classification changed; REVIEW")


if __name__ == "__main__":
    main()
